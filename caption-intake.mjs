import { createHmac } from 'node:crypto';
import { isIP } from 'node:net';

const queue = 'https://synthworx-caption-desk.shaihazher.chatgpt.site/api/intake';
const limit = 3 * 1024 * 1024;

function respond(response, status, body) {
  response.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
  });
  response.end(JSON.stringify(body));
}

export async function captionIntake(request, response) {
  if (request.method !== 'POST') return respond(response, 405, { message: 'Use the Caption Desk intake form.' });
  const origin = request.headers.origin;
  if (origin && origin !== 'https://synthworx.com') return respond(response, 403, { message: 'Open the form on synthworx.com.' });
  if (request.headers['content-type']?.split(';')[0].trim() !== 'application/json') {
    return respond(response, 415, { message: 'Send the diagnostics generated by the form.' });
  }
  const secret = process.env.CAPTION_DESK_INTAKE_RELAY;
  if (!secret) return respond(response, 503, { message: 'Please try again shortly or email hello@synthworx.com.' });
  const tooLarge = () => respond(response, 413, { message: 'The request exceeds 3 MiB. Use the diagnostics email option.' });
  if (Number(request.headers['content-length']) > limit) return tooLarge();
  try {
    let total = 0;
    const chunks = [];
    for await (const chunk of request.iterator({ destroyOnReturn: false })) {
      total += chunk.length;
      if (total > limit) {
        request.resume();
        return tooLarge();
      }
      chunks.push(chunk);
    }
    const ip = request.headers['x-real-ip'];
    const client = typeof ip === 'string' && isIP(ip) ? ip : request.socket.remoteAddress;
    const day = new Date().toISOString().slice(0, 10);
    const digest = createHmac('sha256', secret).update(day + '|' + client).digest('hex');
    const upstream = await fetch(queue, {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-caption-relay': secret, 'x-caption-client': digest },
      body: Buffer.concat(chunks),
      signal: AbortSignal.timeout(25000),
      redirect: 'error',
    });
    const result = await upstream.json();
    if (upstream.ok && !result.receipt) throw Error('Unconfirmed intake');
    return respond(response, upstream.status, result.receipt ? { receipt: result.receipt } : { message: result.message });
  } catch {
    return respond(response, 503, { message: 'Receipt could not be confirmed. Retry the same form or email hello@synthworx.com.' });
  }
}
